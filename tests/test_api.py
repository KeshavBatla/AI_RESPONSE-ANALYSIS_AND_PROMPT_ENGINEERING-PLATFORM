from fastapi.testclient import TestClient

from KeshavBatla import backend_main


client = TestClient(backend_main.app)


def test_health_endpoint():
    response = client.get("/api/health")
    assert response.status_code == 200
    assert response.json() == {"status": "ok"}


def test_generate_rejects_empty_prompt_without_provider_call(monkeypatch):
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    monkeypatch.delenv("DEMO_MODE", raising=False)

    response = client.post("/api/generate", json={"prompt": "   "})
    assert response.status_code == 400
    assert response.json()["detail"] == "Prompt cannot be empty"


def test_analyze_rejects_empty_prompt_or_response():
    empty_prompt = client.post(
        "/api/analyze", json={"prompt": " ", "response": "Answer"}
    )
    empty_response = client.post(
        "/api/analyze", json={"prompt": "Question", "response": ""}
    )
    assert empty_prompt.status_code == 400
    assert empty_response.status_code == 400


def test_analysis_response_schema_contains_five_bounded_scores_and_explanations():
    response = client.post(
        "/api/analyze",
        json={
            "prompt": "Explain photosynthesis in three points",
            "response": "Photosynthesis uses sunlight.\n- Plants make sugar.\n- Oxygen is released.",
        },
    )
    assert response.status_code == 200
    result = response.json()
    assert set(result) == {
        "relevance",
        "clarity",
        "conciseness",
        "completeness",
        "structure",
        "explanations",
    }
    assert all(
        isinstance(result[field], int) and 0 <= result[field] <= 100
        for field in ("relevance", "clarity", "conciseness", "completeness", "structure")
    )
    assert result["explanations"]


def test_generate_without_key_returns_configuration_error(monkeypatch):
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    monkeypatch.setenv("DEMO_MODE", "false")

    response = client.post("/api/generate", json={"prompt": "A valid prompt"})
    assert response.status_code == 503
    assert "GEMINI_API_KEY" in response.json()["detail"]


def test_demo_mode_is_deterministic_and_explicit(monkeypatch):
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    monkeypatch.setenv("DEMO_MODE", "true")

    response = client.post("/api/generate", json={"prompt": "Explain photosynthesis"})
    assert response.status_code == 200
    result = response.json()
    assert result["mode"] == "demo"
    assert result["model"] == "deterministic-demo"
    assert "not generated by an AI model" in result["response"]


def test_live_generation_uses_stubbed_provider_and_returns_live_mode(monkeypatch):
    monkeypatch.setenv("GEMINI_API_KEY", "test-key-not-a-real-secret")
    monkeypatch.delenv("DEMO_MODE", raising=False)
    monkeypatch.setenv("GEMINI_MODEL", backend_main.DEFAULT_MODEL)
    calls = []

    async def fake_provider(prompt, model, api_key):
        calls.append((prompt, model, api_key))
        return "Stubbed response"

    monkeypatch.setattr(backend_main, "call_ai_provider", fake_provider)
    response = client.post("/api/generate", json={"prompt": "A valid prompt"})

    assert response.status_code == 200
    assert response.json() == {
        "response": "Stubbed response",
        "model": backend_main.DEFAULT_MODEL,
        "mode": "live",
    }
    assert calls == [
        ("A valid prompt", backend_main.DEFAULT_MODEL, "test-key-not-a-real-secret")
    ]


def test_provider_failure_returns_generic_error_without_leaking_provider_detail(
    monkeypatch, caplog
):
    monkeypatch.setenv("GEMINI_API_KEY", "test-key-not-a-real-secret")
    monkeypatch.delenv("DEMO_MODE", raising=False)

    async def fail_provider(*_args):
        raise backend_main.AIProviderError("sensitive provider detail")

    monkeypatch.setattr(backend_main, "call_ai_provider", fail_provider)
    response = client.post("/api/generate", json={"prompt": "A valid prompt"})

    assert response.status_code == 502
    assert response.json()["detail"] == (
        "The AI provider could not complete the request. Please try again."
    )
    assert "sensitive provider detail" not in response.text
    assert "sensitive provider detail" not in caplog.text


def test_gemini_sdk_request_and_text_parsing_are_stubbed(monkeypatch):
    calls = {}

    class FakeInteractions:
        def create(self, *, model, input):
            calls["request"] = (model, input)
            return type("FakeResponse", (), {"output_text": "  Gemini response  "})()

    class FakeClient:
        def __init__(self, *, api_key, http_options):
            calls["api_key"] = api_key
            calls["timeout"] = http_options.timeout
            self.interactions = FakeInteractions()

        def __enter__(self):
            return self

        def __exit__(self, *_args):
            calls["closed"] = True

    monkeypatch.setattr(backend_main.genai, "Client", FakeClient)
    text = backend_main._generate_gemini_text(
        "Test prompt", "gemini-3.8-flash", "test-key-not-a-real-secret"
    )

    assert text == "Gemini response"
    assert calls == {
        "api_key": "test-key-not-a-real-secret",
        "timeout": 30_000,
        "request": ("gemini-3.8-flash", "Test prompt"),
        "closed": True,
    }
